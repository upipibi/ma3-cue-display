#!/usr/bin/env bash
# Bundles src/ into one self-contained Lua file for the console. Modules are
# wrapped in package.preload so require() works with no path setup and no src/
# directory present on the console.
set -euo pipefail

# The single source of truth for the version. Nothing else hardcodes it.
VERSION="2.0.0"
XML_VERSION="${VERSION}.0"   # grandMA3 plugin XML wants a 4-part version

LUA=/opt/homebrew/opt/lua@5.4/bin/lua
MODULES=(json state http server ma3)
OUT_LUA="dist/MA3CueDisplay.lua"
OUT_XML="dist/MA3CueDisplay.xml"

cd "$(dirname "$0")"
mkdir -p dist

if [[ ! -x "$LUA" ]]; then
  echo "ERROR: Lua 5.4 not found at $LUA — run: brew install lua@5.4" >&2
  exit 1
fi

# The page is embedded in a [==[ ... ]==] long string. A literal ]==] in the
# HTML would terminate it early and produce a syntax error on the console.
if grep -q ']==]' src/display.html; then
  echo "ERROR: src/display.html contains ]==] which breaks the Lua long string" >&2
  exit 1
fi

# The console has no route to the internet; an external asset would block paint
# and then fail.
if grep -qE 'https?://' src/display.html; then
  echo "ERROR: src/display.html references an external URL" >&2
  exit 1
fi

# Every module main.lua requires must be one we actually bundle. Miss one and
# the bundle still loads on this Mac -- where src/ exists -- and fails only on
# the console.
missing=""
while read -r m; do
  case " ${MODULES[*]} display_html socket " in
    *" $m "*) ;;
    *) missing="$missing $m" ;;
  esac
done < <(grep -oE 'require\("[a-z_]+"\)' src/main.lua | sed 's/require("//;s/")//' | sort -u)
if [[ -n "$missing" ]]; then
  echo "ERROR: main.lua requires modules the build does not bundle:$missing" >&2
  exit 1
fi

{
  echo "-- MA3 Cue Display ${VERSION}"
  echo "-- Generated by build.sh -- do not edit. Source:"
  echo "--   https://github.com/upipibi/ma3-cue-display"
  echo ""
  for m in "${MODULES[@]}"; do
    echo "package.preload[\"${m}\"] = function()"
    cat "src/${m}.lua"
    echo "end"
    echo ""
  done
  echo 'package.preload["display_html"] = function() return [==['
  cat src/display.html
  echo ']==] end'
  echo ""
  echo "MA3CUEDISPLAY_VERSION = \"${VERSION}\""
  echo ""
  cat src/main.lua
} > "$OUT_LUA"

sed "s/@@XML_VERSION@@/${XML_VERSION}/" src/plugin.xml.template > "$OUT_XML"

# Load the bundle for real, with the MA3 globals stubbed, and confirm the
# modules resolve and the entry point comes back. A syntax check alone would
# miss a package.preload name that does not match its require.
"$LUA" - "$OUT_LUA" <<'VERIFY'
local path = arg[1]
local chunk = assert(loadfile(path))
Printf = function() end
GetVar = function() return 0 end
SetVar = function() end
GlobalVars = function() return {} end
local entry = chunk()
assert(type(entry) == "function", "entry point is not a function")
assert(#require("display_html") > 1000, "display page did not embed")
assert(require("json").encode({ a = 1 }) == '{"a":1}', "json module broken")
assert(require("ma3").format_cue_number(12500) == "12.5", "ma3 module broken")
assert(require("state").new().displayed.cueNumber == "--", "state module broken")
assert(require("http").parse_request("GET / HTTP/1.1").path == "/", "http module broken")
assert(type(require("server").tick) == "function", "server module broken")
print("bundle verified: modules resolve, page embedded, entry point returned")
VERIFY

echo "built ${OUT_LUA} ($(wc -c < "$OUT_LUA" | tr -d ' ') bytes)"
echo "built ${OUT_XML} (plugin ${XML_VERSION})"
