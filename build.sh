#!/usr/bin/env bash
# Bundles src/ into one self-contained Lua file for the console.
#
# The bundle carries its own module table and its own require, and never touches
# package.preload or package.loaded. On a console those are shared by every
# plugin and keep whatever was loaded earlier in the session: the previous
# version of this plugin, another plugin's modules, the console's own "json".
# The first 2.1.0 build used package.preload; on the desk require() handed it
# 2.0's modules, every tick failed and the plugin shut itself down.
set -euo pipefail

# The single source of truth for the version. Nothing else hardcodes it.
VERSION="2.1.0"
XML_VERSION="${VERSION}.0"   # grandMA3 plugin XML wants a 4-part version

# The console runs Lua 5.5 on grandMA3 2.5; 5.4 is kept as a check for older software.
LUA=/opt/homebrew/opt/lua@5.5/bin/lua
LUA_COMPAT=/opt/homebrew/opt/lua@5.4/bin/lua
MODULES=(json state http server ma3)
OUT_LUA="dist/MA3CueDisplay.lua"
OUT_XML="dist/MA3CueDisplay.xml"

cd "$(dirname "$0")"
mkdir -p dist

for l in "$LUA" "$LUA_COMPAT"; do
  if [[ ! -x "$l" ]]; then
    echo "ERROR: Lua not found at $l — run: brew install lua@5.5 lua@5.4" >&2
    exit 1
  fi
done

# The page is embedded in a [==[ ... ]==] long string. A literal ]==] in the
# HTML would terminate it early and produce a syntax error on the console.
if grep -q ']==]' src/display.html; then
  echo "ERROR: src/display.html contains ]==] which breaks the Lua long string" >&2
  exit 1
fi

# The console has no route to the internet; an external asset would block paint
# and then fail.
if grep -qE 'https?://' src/display.html; then
  echo "ERROR: src/display.html references an external URL" >&2
  exit 1
fi

# Every module main.lua requires must be one we actually bundle. Miss one and
# the bundle still loads on this Mac -- where src/ exists -- and fails only on
# the console.
missing=""
while read -r m; do
  case " ${MODULES[*]} display_html socket " in
    *" $m "*) ;;
    *) missing="$missing $m" ;;
  esac
done < <(grep -oE 'require\("[a-z_]+"\)' src/main.lua | sed 's/require("//;s/")//' | sort -u)
if [[ -n "$missing" ]]; then
  echo "ERROR: main.lua requires modules the build does not bundle:$missing" >&2
  exit 1
fi

{
  echo "-- MA3 Cue Display ${VERSION}"
  echo "-- Generated by build.sh -- do not edit. Source:"
  echo "--   https://github.com/upipibi/ma3-cue-display"
  echo ""
  # Private module table. __require resolves bundled names first and hands
  # anything else (socket) to the console's require.
  cat <<'LOADER'
local __host_require = require
local __modules, __loaded = {}, {}
local function __require(name)
  local m = __loaded[name]
  if m ~= nil then return m end
  local build = __modules[name]
  if build == nil then return __host_require(name) end
  m = build(__require)
  if m == nil then m = true end
  __loaded[name] = m
  return m
end

LOADER
  # Each module takes `require` as a parameter, so the require() calls in its
  # source reach the private table instead of the console's global one.
  for m in "${MODULES[@]}"; do
    echo "__modules[\"${m}\"] = function(require)"
    cat "src/${m}.lua"
    echo "end"
    echo ""
  done
  echo '__modules["display_html"] = function() return [==['
  cat src/display.html
  echo ']==] end'
  echo ""
  # Build-time check hook: build.sh sets this global before loading the bundle
  # to inspect the modules it resolved. Nothing sets it on a console.
  echo 'if MA3CUEDISPLAY_VERIFY then MA3CUEDISPLAY_VERIFY(__require) end'
  echo ""
  # Locals, not globals: a global would be shared with every other plugin.
  echo "local MA3CUEDISPLAY_VERSION = \"${VERSION}\""
  echo 'local require = __require'
  echo ""
  cat src/main.lua
} > "$OUT_LUA"

sed "s/@@XML_VERSION@@/${XML_VERSION}/" src/plugin.xml.template > "$OUT_XML"

# Load the bundle for real, with the MA3 globals stubbed, and confirm the
# modules resolve and the entry point comes back. A syntax check alone would
# miss a module name that does not match its require.
#
# The Lua state is made dirty first, the way a console's is: stale modules under
# every name the bundle uses sit in package.loaded and package.preload. The
# bundle must resolve its own modules anyway and must leave package.* alone.
verify_bundle() {
"$1" - "$OUT_LUA" <<'VERIFY'
local path = arg[1]
local chunk = assert(loadfile(path))
Printf = function() end
GetVar = function() return 0 end
SetVar = function() end
GlobalVars = function() return {} end

local names = { "json", "state", "http", "server", "ma3", "display_html" }
local stale = {}
for _, name in ipairs(names) do
  stale[name] = { stale_module = name }
  package.loaded[name] = stale[name]
  package.preload[name] = function() return stale[name] end
end

local checked = false
MA3CUEDISPLAY_VERIFY = function(req)
  assert(#req("display_html") > 1000, "display page did not embed")
  local json = req("json")
  assert(json.encode({ a = 1 }) == '{"a":1}', "json module broken")
  assert(json.encode({ json.null }) == "[null]", "json.null missing: a stale json module was resolved")
  assert(req("ma3").format_cue_number(12500) == "12.5", "ma3 module broken")
  local state = req("state")
  assert(state.new().displayed.cueNumber == "--", "state module broken")
  assert(type(state.update_timecode) == "function", "state.update_timecode missing: a stale state module was resolved")
  assert(#state.payload(state.new(), "v", 1).grid == 8, "state and json do not share one json module")
  assert(req("http").parse_request("GET /grid HTTP/1.1").path == "/grid", "http module broken")
  assert(type(req("server").tick) == "function", "server module broken")
  checked = true
end

local entry = chunk()
assert(checked, "the bundle did not call the verify hook")
assert(type(entry) == "function", "entry point is not a function")
for _, name in ipairs(names) do
  assert(package.loaded[name] == stale[name], "the bundle replaced package.loaded." .. name)
end
assert(rawget(_G, "MA3CUEDISPLAY_VERSION") == nil, "the bundle leaked a global")
print("bundle verified on " .. _VERSION .. ": own modules resolved in a dirty Lua state, page embedded, entry point returned")
VERIFY
}
verify_bundle "$LUA"
verify_bundle "$LUA_COMPAT"

echo "built ${OUT_LUA} ($(wc -c < "$OUT_LUA" | tr -d ' ') bytes)"
echo "built ${OUT_XML} (plugin ${XML_VERSION})"
